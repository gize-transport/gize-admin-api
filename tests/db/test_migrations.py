import sys
from pathlib import Path

import asyncpg
import pytest
from alembic import command
from alembic.util.exc import AutogenerateDiffsDetected
from sqlalchemy import Column, Integer, MetaData, String, Table

from gize_api.core.migrations import MIGRATION_LOCK_ID
from tests.support import ROOT, DatabaseUrls, alembic_config, run_migrations


async def _revision(url: str) -> str | None:
    conn = await asyncpg.connect(url, timeout=3)
    try:
        revision: str | None = await conn.fetchval("SELECT version_num FROM gize.alembic_version")
        return revision
    finally:
        await conn.close()


def test_upgrade_downgrade_upgrade(scratch_database: DatabaseUrls) -> None:
    run_migrations(scratch_database.migrator, "head")
    run_migrations(scratch_database.migrator, "base", downgrade=True)
    run_migrations(scratch_database.migrator, "head")


async def test_head_is_recorded(database: DatabaseUrls) -> None:
    assert await _revision(database.migrator) is not None


def _probe_metadata() -> MetaData:
    metadata = MetaData(schema="gize")
    Table("probe", metadata, Column("id", Integer, primary_key=True), Column("label", String(20)))
    return metadata


async def _execute(url: str, statement: str) -> None:
    conn = await asyncpg.connect(url, timeout=3)
    try:
        await conn.execute(statement)
    finally:
        await conn.close()


async def test_alembic_compares_the_gize_schema_and_ignores_others(
    scratch_database: DatabaseUrls,
) -> None:
    """`alembic check` sees tables in `gize` (and only there): a matching table is no diff."""
    await asyncio.to_thread(run_migrations, scratch_database.migrator, "head")
    config = alembic_config(scratch_database.migrator, target_metadata=_probe_metadata())
    with pytest.raises(AutogenerateDiffsDetected):
        await asyncio.to_thread(command.check, config)  # the model's table does not exist yet

    await _execute(
        scratch_database.migrator,
        "CREATE TABLE gize.probe (id serial PRIMARY KEY, label varchar(20))",
    )
    await _execute(scratch_database.admin, "CREATE TABLE public.not_ours (id int)")
    await asyncio.to_thread(command.check, config)  # no diff: gize.probe matches, public isn't ours


def test_models_registry_imports_every_domain_models_module() -> None:
    """Alembic only sees models that gize_api.models imports."""
    package = ROOT / "src" / "gize_api"
    expected = {
        ".".join(path.relative_to(package.parent).with_suffix("").parts)
        for path in package.rglob("models.py")
        if path.parent != package / "core" and path != package / "models.py"
    }
    tree = ast.parse((package / "models.py").read_text())
    imported: set[str] = set()
    for node in ast.walk(tree):
        if isinstance(node, ast.ImportFrom) and node.module:
            imported |= {node.module} | {f"{node.module}.{alias.name}" for alias in node.names}
        elif isinstance(node, ast.Import):
            imported |= {alias.name for alias in node.names}
    assert expected <= imported


async def test_a_second_concurrent_migration_is_refused(scratch_database: DatabaseUrls) -> None:
    holder = await asyncpg.connect(scratch_database.migrator, timeout=3)
    try:
        await holder.execute("SELECT pg_advisory_lock($1)", MIGRATION_LOCK_ID)
        with pytest.raises(SystemExit, match="another migration is running"):
            await asyncio.to_thread(run_migrations, scratch_database.migrator, "head")
    finally:
        await holder.close()
    # The lock went with the holder's connection.
    await asyncio.to_thread(run_migrations, scratch_database.migrator, "head")


def test_migration_settings_are_validated(scratch_database: DatabaseUrls) -> None:
    with pytest.raises(SystemExit, match="must connect as gize_migrator"):
        run_migrations(scratch_database.app, "head")
    config = alembic_config(scratch_database.migrator, app_env="staging")
    with pytest.raises(SystemExit, match="ssl=verify-full"):
        command.upgrade(config, "head")


def test_a_new_revision_passes_lint(tmp_path: Path) -> None:
    """Generated revisions are cleaned by ruff (post-write hook) and pass the repo's lint."""
    config = alembic_config("unused")
    config.set_main_option("version_locations", str(tmp_path))
    command.revision(config, message="probe", rev_id="9999")
    (revision,) = tmp_path.glob("9999_*.py")
    result = subprocess.run(  # noqa: S603 - fixed arguments
        [sys.executable, "-m", "ruff", "check", "--no-cache", str(revision)],
        capture_output=True,
        text=True,
        check=False,
        cwd=ROOT,
    )
    assert result.returncode == 0, result.stdout
